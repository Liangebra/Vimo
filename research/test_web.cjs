const assert = require("node:assert/strict");
require("./core.js");
require("./signal.js");
const C = globalThis.VimoCore, S = globalThis.VimoSignal;
const seq = C.parse(C.demo()), r = C.analyze(seq, .5);
assert.equal(r.rows.length, 90);
assert.equal(r.report.metrics.left_knee_deg.valid_frames, 80);
assert.equal(r.report.metrics.right_knee_deg.valid_frames, 90);
assert.equal(C.angle([1,0],[0,0],[0,1]),90);
assert.equal(C.angle([0,0],[0,0],[0,1]),null);
assert.throws(()=>C.parse("frame,time_s,landmark,x,y,visibility\n0,0,1,NaN,0,1"));
assert.deepEqual(S.filter([1,100,1,null,5,9,5],3,"median"),[50.5,1,50.5,null,7,5,7]);
assert.throws(()=>S.filter([1,2],4));
const times=Array.from({length:120},(_,i)=>i/30), y=times.map(t=>20*Math.sin(2*Math.PI*2*t));
const peak=S.spectrum(times,y).bins.reduce((a,b)=>a.amplitude_deg>b.amplitude_deg?a:b);
assert.ok(Math.abs(peak.frequency_hz-2)<1e-9);
assert.throws(()=>S.spectrum(times,y.map((v,i)=>i===3?null:v)));
assert.throws(()=>S.spectrum(times.map((t,i)=>i===2?t+.02:t),y));
const d=S.dtw([1,2,3],[1,1,2,3]);
assert.equal(d.total_cost_deg,0);
assert.deepEqual(d.path,[[0,0],[0,1],[1,2],[2,3]]);
assert.throws(()=>S.dtw([1,null],[1]));
assert.equal(S.benchmark().results.length,7);
require("./validation.js");
const V=globalThis.VimoValidation, pair=V.demo(), report=V.compare(pair.pred,pair.ref);
assert.equal(report.paired_frames,57);
assert.equal(report.mae_deg,2);
assert.equal(report.rmse_deg,2);
assert.equal(V.compare([{time_s:.5,angle_deg:10}],[{time_s:0,angle_deg:10},{time_s:1,angle_deg:10}],0,.1).paired_frames,0);
assert.equal(S.longest([{frame:0,k:1},{frame:2,k:2},{frame:3,k:3}],"k").length,2);
console.log("Vimo web core checks passed");
